function prm = build_sim_params(cfg)
%BUILD_SIM_PARAMS Flatten cfg into the variables fusion_sim.slx resolves by name.
%
%   Block dialogs read cfg directly. MATLAB Function blocks cannot -- their
%   Parameter data is a bare-name lookup and does not support nested structs,
%   so each block gets one flat struct of double scalars.

    dt = cfg.sim.dt_imu;

    % gnss_schedule (receiver state machine). The last three fields are
    % used by the Option T schedule; the original scheduler ignores them.
    prm.sched_prm = struct( ...
        'dt',       dt, ...
        'T_active', cfg.gnss.T_active, ...
        'T_sleep',  cfg.gnss.T_sleep, ...
        'f_gnss',   cfg.gnss.f_gnss, ...
        'T_warmup', cfg.ctrl.T_warmup, ...
        't_reacq',  cfg.ctrl.t_reacq, ...
        'T_sleep0', cfg.ctrl.T_sleep0 );

    prm.eskf_prm = struct( ...
            'dt',      dt, ...
            'R_sigma', cfg.eskf.R_sigma, ...
            'Rv_sigma', cfg.eskf.Rv_sigma, ...
            'Na',      cfg.imu.meas.Na, ...
            'Ng',      cfg.imu.meas.Ng, ...
            'Ka',      cfg.imu.meas.Ka, ...
            'Kg',      cfg.imu.meas.Kg, ...
            'Q_scale', cfg.eskf.Q_scale);

    prm.ins_prm = struct( ...
        'dt',       dt, ...
        'accelInv', cfg.imu.accelInv, ...
        'feedback', double(cfg.eskf.feedback));

    % coast_cross (crossing-time monitor)
    prm.cross_prm = struct( ...
        'dt',        dt, ...
        'sigma_set', cfg.ctrl.sigma_set, ...
        'n_skip',    cfg.ctrl.n_skip );

    % sleep_ctrl (sleep-length controller)
    prm.ctrl_prm = struct( ...
        'open_loop',    double(cfg.ctrl.open_loop), ...
        'T_fix',        cfg.ctrl.T_fix, ...
        'T_sleep0',     cfg.ctrl.T_sleep0, ...
        'T_min',        cfg.ctrl.T_min, ...
        'T_max',        cfg.ctrl.T_max, ...
        'dT_default',   cfg.ctrl.dT_default, ...
        'Ki',           cfg.ctrl.Ki, ...
        'Kp',           cfg.ctrl.Kp, ...
        'adapt_en',     cfg.ctrl.adapt_en, ...
        'sigma_set',    cfg.ctrl.sigma_set, ...
        'm_fix',        cfg.ctrl.m_fix);

        % gnss_degrade
    assert(numel(cfg.gnss.deg.t) == numel(cfg.gnss.deg.k), 'deg.t and deg.k must match');
    assert(cfg.gnss.deg.t(1) == 0 && all(diff(cfg.gnss.deg.t) > 0), 'deg.t must start at 0 and increase');
    prm.deg_prm = struct( ...
        'en',    double(cfg.gnss.deg.en), ...
        't',     cfg.gnss.deg.t(:)', ...
        'k',     cfg.gnss.deg.k(:)', ...
        'k_out', cfg.gnss.deg.k_out);

    % Unit Delay initial conditions
    prm.ins_x0  = [0; 0; cfg.traj.V0; 0; cfg.traj.psi0; 0; 0; 0] + cfg.ins.x0_err;
    prm.eskf_P0 = diag(cfg.eskf.P0_diag);
    
end